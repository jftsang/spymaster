#!/usr/bin/env bash
set -euo pipefail

# Regenerate the Android release keystore, save its secrets locally, and set
# the matching GitHub Actions secrets. Run from anywhere in this repository.

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

KEYSTORE="${KEYSTORE:-/Users/jmft2/Documents/spymaster.jks}"
SECRETS_FILE="${SECRETS_FILE:-.secrets}"
ALIAS="${ANDROID_KEY_ALIAS:-spymaster}"
STORE_PASSWORD="${ANDROID_KEYSTORE_PASSWORD:-$(openssl rand -hex 24)}"
KEY_PASSWORD="${ANDROID_KEY_PASSWORD:-$(openssl rand -hex 24)}"

for cmd in keytool gh base64 openssl tr; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
        echo "Missing required command: $cmd" >&2
        exit 1
    fi
done

if ! gh auth status >/dev/null 2>&1; then
    echo "GitHub CLI is not authenticated. Run 'gh auth login' first." >&2
    exit 1
fi

if ! gh repo view >/dev/null 2>&1; then
    echo "Run this script from inside a Git repository with a GitHub remote." >&2
    exit 1
fi

prompt() {
    local label="$1"
    local default="${2:-}"
    local value=""

    if [[ -n "$default" ]]; then
        read -r -p "$label [$default]: " value
        printf '%s' "${value:-$default}"
    else
        while [[ -z "$value" ]]; do
            read -r -p "$label: " value
        done
        printf '%s' "$value"
    fi
}

DEFAULT_NAME="$(git config user.name || true)"

echo "Regenerating Android release signing key."
echo "Keystore: $KEYSTORE"
echo "Alias:    $ALIAS"
echo

NAME="$(prompt "Full name" "$DEFAULT_NAME")"
ORG_UNIT="$(prompt "Organizational unit" "Engineering")"
ORG="$(prompt "Organization" "Spymaster")"
CITY="$(prompt "City or locality")"
STATE="$(prompt "State or province")"
COUNTRY="$(prompt "Country code (e.g. GB)" "GB")"

if ! [[ "$COUNTRY" =~ ^[A-Za-z]{2}$ ]]; then
    echo "Country code must be two letters." >&2
    exit 1
fi
COUNTRY="$(printf '%s' "$COUNTRY" | tr '[:lower:]' '[:upper:]')"

mkdir -p "$(dirname "$KEYSTORE")"

if [[ -e "$KEYSTORE" ]]; then
    BACKUP="${KEYSTORE}.$(date +%Y%m%d%H%M%S).bak"
    mv "$KEYSTORE" "$BACKUP"
    echo "Backed up previous keystore to $BACKUP"
fi

keytool -genkeypair -v \
    -keystore "$KEYSTORE" \
    -storetype JKS \
    -alias "$ALIAS" \
    -keyalg RSA \
    -keysize 2048 \
    -validity 10000 \
    -storepass "$STORE_PASSWORD" \
    -keypass "$KEY_PASSWORD" \
    -dname "CN=$NAME, OU=$ORG_UNIT, O=$ORG, L=$CITY, ST=$STATE, C=$COUNTRY"

KEYSTORE_B64="$(base64 -i "$KEYSTORE" -o - | tr -d '\n')"

if ! grep -qxF '.secrets' .gitignore; then
    printf '\n.secrets\n' >> .gitignore
fi

umask 077
cat > "$SECRETS_FILE" <<EOF
# Generated by scripts/setup-android-signing.sh -- do not commit.
ANDROID_KEYSTORE=$KEYSTORE_B64
ANDROID_KEYSTORE_PASSWORD=$STORE_PASSWORD
ANDROID_KEY_ALIAS=$ALIAS
ANDROID_KEY_PASSWORD=$KEY_PASSWORD
EOF
chmod 600 "$SECRETS_FILE"

printf '%s' "$KEYSTORE_B64" | gh secret set ANDROID_KEYSTORE
printf '%s' "$STORE_PASSWORD" | gh secret set ANDROID_KEYSTORE_PASSWORD
printf '%s' "$ALIAS" | gh secret set ANDROID_KEY_ALIAS
printf '%s' "$KEY_PASSWORD" | gh secret set ANDROID_KEY_PASSWORD

echo
echo "Wrote $SECRETS_FILE with mode 600."
echo "Set ANDROID_KEYSTORE, ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS, and ANDROID_KEY_PASSWORD on GitHub."
